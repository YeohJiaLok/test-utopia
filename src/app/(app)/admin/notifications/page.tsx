import Link from "next/link";
import { ArrowRight, MessageCircle, Send } from "lucide-react";
import { buttonVariants } from "@/components/ui/button";
import { requireUser } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import type { Notification, NotificationAudience } from "@/lib/types";
import { PageHeader } from "@/components/shared/page-header";
import { EmptyState } from "@/components/shared/empty-state";
import { FadeIn, Stagger, StaggerItem } from "@/components/motion";
import { AUDIENCE_LABEL, WhatsAppMessage, type OutboxItem } from "@/components/admin/whatsapp-log";
import { cn } from "@/lib/utils";

export const metadata = { title: "WhatsApp outbox · Sejuk Ops" };

const AUDIENCES = Object.keys(AUDIENCE_LABEL) as NotificationAudience[];
const STATUSES: Notification["status"][] = ["pending", "opened", "sent", "read"];

function first(v: string | string[] | undefined) {
  return (Array.isArray(v) ? v[0] : v) ?? "";
}

function href(audience: string, status: string) {
  const p = new URLSearchParams();
  if (audience) p.set("audience", audience);
  if (status) p.set("status", status);
  const qs = p.toString();
  return qs ? `/admin/notifications?${qs}` : "/admin/notifications";
}

export default async function WhatsAppOutboxPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  await requireUser(["admin"]);
  const sp = await searchParams;
  const audienceParam = first(sp.audience);
  const statusParam = first(sp.status);
  const audience = (AUDIENCES as string[]).includes(audienceParam) ? (audienceParam as NotificationAudience) : "";
  const status = (STATUSES as string[]).includes(statusParam) ? (statusParam as Notification["status"]) : "";

  const supabase = await createClient();
  let list = supabase
    .from("notifications")
    .select("*, order:orders(id, order_no)")
    .eq("channel", "whatsapp")
    .order("created_at", { ascending: false })
    .limit(100);
  if (audience) list = list.eq("audience", audience);
  if (status) list = list.eq("status", status);

  const countFor = async (patch: { audience?: string; status?: string }) => {
    let q = supabase.from("notifications").select("id", { count: "exact", head: true }).eq("channel", "whatsapp");
    if (patch.audience) q = q.eq("audience", patch.audience);
    if (patch.status) q = q.eq("status", patch.status);
    return (await q).count ?? 0;
  };

  const [{ data, error }, audienceCounts, statusCounts] = await Promise.all([
    list,
    Promise.all(["", ...AUDIENCES].map(async (a) => [a, await countFor({ audience: a, status })] as const)),
    Promise.all(STATUSES.map(async (s) => [s, await countFor({ audience, status: s })] as const)),
  ]);

  const items: OutboxItem[] = ((data ?? []) as Record<string, unknown>[]).map((n) => ({
    ...(n as unknown as Notification),
    order: ((Array.isArray(n.order) ? n.order[0] : n.order) as OutboxItem["order"]) ?? null,
  }));
  const aCounts = Object.fromEntries(audienceCounts) as Record<string, number>;
  const sCounts = Object.fromEntries(statusCounts) as Record<string, number>;
  const audienceTabs = ["", ...AUDIENCES.filter((a) => aCounts[a] || a === "customer" || a === "technician")];

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="Notifications"
        title="WhatsApp outbox"
        description="Messages generated by workflow triggers — technician job cards on assignment and customer feedback requests on Job Done. Open one to send it from WhatsApp."
      />

      {(sCounts.pending ?? 0) > 0 && status !== "pending" && (
        <FadeIn className="flex flex-col gap-3 rounded-xl border border-amber-500/25 bg-amber-500/[0.06] p-4 sm:flex-row sm:items-center">
          <span className="flex size-9 shrink-0 items-center justify-center rounded-lg bg-amber-500/15 text-amber-700 dark:text-amber-300">
            <Send className="size-4" />
          </span>
          <div className="min-w-0 flex-1">
            <p className="text-sm font-semibold">
              <span className="tabular">{sCounts.pending}</span> message{sCounts.pending === 1 ? "" : "s"} waiting to be sent
            </p>
            <p className="text-muted-foreground text-xs">
              Messages open pre-filled in WhatsApp on this device. Tap one to send it; it is marked as opened automatically.
            </p>
          </div>
          <Link
            href={href(audience, "pending")}
            className={cn(buttonVariants({ variant: "outline" }), "bg-background h-11 shrink-0 sm:h-9")}
          >
            Review pending <ArrowRight />
          </Link>
        </FadeIn>
      )}

      <div className="bg-card flex flex-col gap-2 rounded-xl border p-1.5 shadow-xs md:flex-row md:items-center md:justify-between">
        <nav className="-mx-1.5 flex gap-1 overflow-x-auto px-1.5 [scrollbar-width:none] md:mx-0 md:px-0" aria-label="Filter by audience">
          {audienceTabs.map((a) => {
            const active = audience === a;
            return (
              <Link
                key={a || "all"}
                href={href(a, status)}
                aria-current={active ? "page" : undefined}
                className={cn(
                  "inline-flex h-10 shrink-0 items-center gap-1.5 rounded-lg px-3 text-sm font-medium transition-colors md:h-8",
                  active ? "bg-primary/8 text-primary ring-primary/15 ring-1 ring-inset" : "text-muted-foreground hover:bg-muted hover:text-foreground",
                )}
              >
                {a ? AUDIENCE_LABEL[a as NotificationAudience] : "All"}
                <span className={cn("rounded-full px-1.5 text-[11px] font-semibold tabular", active ? "bg-primary/12" : "bg-muted")}>
                  {(aCounts[a] ?? 0).toLocaleString("en-MY")}
                </span>
              </Link>
            );
          })}
        </nav>
        <div className="flex flex-wrap items-center gap-1.5 border-t px-1 pt-2 pb-1 md:border-t-0 md:p-0 md:pr-1" role="group" aria-label="Filter by status">
          <span className="text-muted-foreground mr-1 text-xs">Status</span>
          {STATUSES.filter((s) => sCounts[s] || s === "pending" || s === "opened").map((s) => {
            const active = status === s;
            return (
              <Link
                key={s}
                href={href(audience, active ? "" : s)}
                aria-current={active ? "true" : undefined}
                className={cn(
                  "inline-flex h-9 items-center gap-1.5 rounded-full border px-3 text-xs font-medium capitalize transition-colors md:h-7 md:px-2.5",
                  active ? "border-primary/40 bg-primary/8 text-primary" : "text-muted-foreground hover:bg-muted",
                )}
              >
                <span
                  className={cn(
                    "size-1.5 rounded-full",
                    s === "pending" ? "bg-amber-500" : s === "opened" ? "bg-sky-500" : "bg-emerald-500",
                  )}
                />
                {s}
                <span className="tabular">{(sCounts[s] ?? 0).toLocaleString("en-MY")}</span>
              </Link>
            );
          })}
        </div>
      </div>

      {error ? (
        <EmptyState icon={MessageCircle} title="Couldn't load the outbox" description={error.message} />
      ) : items.length ? (
        <>
          <Stagger className="grid gap-3 md:grid-cols-2 2xl:grid-cols-3" step={0.03}>
            {items.map((n) => (
              <StaggerItem
                key={n.id}
                className={cn(
                  "bg-card rounded-xl border p-4 shadow-xs transition-shadow hover:shadow-md",
                  n.status === "pending" && "border-amber-500/30 ring-1 ring-amber-500/10",
                )}
              >
                <WhatsAppMessage n={n} showOrder />
              </StaggerItem>
            ))}
          </Stagger>
          {items.length === 100 && (
            <p className="text-muted-foreground text-center text-xs">Showing the latest 100 messages.</p>
          )}
        </>
      ) : (
        <EmptyState
          icon={MessageCircle}
          title="Outbox is empty"
          description={
            audience || status
              ? "No WhatsApp messages match this filter."
              : "Assign a technician or complete a job and the WhatsApp message will appear here."
          }
        />
      )}
    </div>
  );
}
